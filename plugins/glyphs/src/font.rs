/// The rows of `c` (upper-cased), or `None` if the font lacks it.
pub fn glyph(c: char) -> Option<&'static [&'static str; HEIGHT]> {
    let c = c.to_ascii_uppercase();
    GLYPHS.iter().find(|(g, _)| *g == c).map(|(_, rows)| rows)
}

/// `text` as a grid of set cells, `width * HEIGHT`, row by row; characters
/// the font lacks are left out.
pub fn rasterize(text: &str) -> (usize, Vec<bool>) {
    let glyphs: Vec<_> = text.chars().filter_map(glyph).collect();
    let width = (glyphs.len() * (WIDTH + 1)).saturating_sub(1);
    let mut cells = vec![false; width * HEIGHT];
    for (i, rows) in glyphs.iter().enumerate() {
        for (y, row) in rows.iter().enumerate() {
            for (x, b) in row.bytes().enumerate() {
                if b == b'#' {
                    cells[y * width + i * (WIDTH + 1) + x] = true;
                }
            }
        }
    }
    (width, cells)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_glyph_is_five_by_seven() {
        for (c, rows) in GLYPHS {
            for row in rows {
                assert_eq!(row.len(), WIDTH, "{c:?}");
                assert!(row.bytes().all(|b| b == b'#' || b == b'.'), "{c:?}");
            }
        }
    }

    #[test]
    fn letters_digits_and_key_punctuation_are_there() {
        for c in ('A'..='Z').chain('0'..='9').chain(",./;'[]-=`\\+↑↓←→".chars()) {
            assert!(glyph(c).is_some(), "{c:?}");
        }
        assert!(glyph('a').is_some(), "lower case reads as upper");
    }

    #[test]
    fn glyphs_differ() {
        let mut seen = std::collections::HashSet::new();
        for (c, rows) in GLYPHS {
            assert!(seen.insert(rows.concat()), "{c:?} looks like another glyph");
        }
    }

    #[test]
    fn rasterize_spaces_characters() {
        let (w, cells) = rasterize("I1");
        assert_eq!(w, 11);
        assert_eq!(cells.len(), 11 * HEIGHT);
        // Column 5 is the gap between the two.
        assert!((0..HEIGHT).all(|y| !cells[y * w + 5]));
        assert_eq!(rasterize("").0, 0);
    }
}
